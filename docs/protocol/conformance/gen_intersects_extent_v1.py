def to_be(wkb: bytes) -> bytes:
    """Rewrite little-endian ISO WKB as big-endian."""
    out = bytearray(); pos = 0
    def rd(fmt):
        nonlocal pos
        v = struct.unpack_from("<" + fmt, wkb, pos); pos += struct.calcsize(fmt); return v
    def geom():
        nonlocal pos
        assert wkb[pos] == 1; pos += 1; out.append(0)
        (t,) = rd("I"); out.extend(struct.pack(">I", t))
        base, dims = t % 1000, 2 + {0: 0, 1: 1, 2: 1, 3: 2}[t // 1000]
        def pts(n):
            for _ in range(n * dims): out.extend(struct.pack(">d", rd("d")[0]))
        if base == 1: pts(1)
        elif base == 2: (n,) = rd("I"); out.extend(struct.pack(">I", n)); pts(n)
        elif base == 3:
            (r,) = rd("I"); out.extend(struct.pack(">I", r))
            for _ in range(r): (n,) = rd("I"); out.extend(struct.pack(">I", n)); pts(n)
        elif base in (4, 5, 6, 7):
            (n,) = rd("I"); out.extend(struct.pack(">I", n))
            for _ in range(n): geom()
        else: raise ValueError(t)
    geom(); assert pos == len(wkb); return bytes(out)

con = duckdb.connect(); con.execute("LOAD spatial")
version = con.execute("SELECT version(), (SELECT extension_version FROM duckdb_extensions() WHERE extension_name='spatial')").fetchall()[0]
geoms = []
for name, wkt in WKT:
    le = bytes(con.execute("SELECT ST_AsWKB(?::GEOMETRY)", [wkt]).fetchall()[0][0])
    be = to_be(le)
    # round-trip check: DuckDB reads the BE bytes as the same geometry
    same = con.execute("SELECT ST_AsWKB(ST_GeomFromWKB(?)) = ?", [be, le]).fetchall()[0][0]
    assert same, name
    geoms.append({"name": name, "wkt": wkt, "wkb_le": le.hex(), "wkb_be": be.hex()})
cases = []
for a in geoms:
    for b in geoms:
        r = con.execute("SELECT ST_GeomFromWKB(from_hex(?)) && ST_GeomFromWKB(from_hex(?))", [a["wkb_le"], b["wkb_le"]]).fetchall()[0][0]
        cases.append({"left": a["name"], "right": b["name"], "expected": r})
doc = {
  "description": "duckdb.spatial/intersects_extent@1 (`a && b`) results from DuckDB core. An SDK evaluator must return `expected` for every case, for both the little-endian (wkb_le) and big-endian (wkb_be) encodings of each side. Generated by gen_intersects_extent_v1.py.",
  "duckdb_version": version[0], "spatial_version": version[1],
  "geometries": geoms, "cases": cases}
json.dump(doc, open(sys.argv[1], "w"), indent=1)
print(len(geoms), "geometries,", len(cases), "cases,", sum(c["expected"] for c in cases), "true")
