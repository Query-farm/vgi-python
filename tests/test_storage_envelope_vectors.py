"""The storage-envelope test vectors match this implementation.

``vgi/_test_fixtures/storage_envelope_v1.json`` is generated by
``scripts/gen_storage_envelope_vectors.py``; the vgi extension carries a
verbatim copy at ``test/vectors/storage_envelope_v1.json`` for other SDKs.
"""

from __future__ import annotations

import importlib.util
import json
import os
from pathlib import Path
from typing import Any

import pytest

from vgi.function_storage_blobs import (
    TAG_POINTER,
    StorageEnvelopeError,
    decode_pointer,
    envelope_tag,
)

_ROOT = Path(__file__).resolve().parent.parent
_VECTORS_PATH = _ROOT / "vgi" / "_test_fixtures" / "storage_envelope_v1.json"
VECTORS: dict[str, Any] = json.loads(_VECTORS_PATH.read_text())


def _generator() -> Any:
    spec = importlib.util.spec_from_file_location(
        "gen_storage_envelope_vectors", _ROOT / "scripts" / "gen_storage_envelope_vectors.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_vectors_file_is_current() -> None:
    """Regenerate with scripts/gen_storage_envelope_vectors.py after a format change."""
    assert _VECTORS_PATH.read_text() == _generator().render()


def test_vgi_extension_copy_matches() -> None:
    """The vgi extension's copy (when checked out next to this repo, or at $VGI_DIR) is identical."""
    vgi_dir = Path(os.environ.get("VGI_DIR", str(_ROOT.parent / "vgi")))
    copy = vgi_dir / "test" / "vectors" / "storage_envelope_v1.json"
    if not copy.is_file():
        pytest.skip(f"no vgi checkout with {copy}")
    assert copy.read_text() == _VECTORS_PATH.read_text()


@pytest.mark.parametrize("case", VECTORS["inline"], ids=lambda c: c["name"])
def test_inline_cases_decode(case: dict[str, str]) -> None:
    """Inline envelopes are the tag then the raw bytes."""
    envelope = bytes.fromhex(case["envelope_hex"])
    assert envelope_tag(envelope) == VECTORS["tag_inline"]
    assert envelope[1:] == bytes.fromhex(case["value_hex"])


@pytest.mark.parametrize("case", VECTORS["pointers"], ids=lambda c: c["name"])
def test_pointer_cases_decode(case: dict[str, Any]) -> None:
    """Pointer envelopes decode to their object id, size and sha256."""
    envelope = bytes.fromhex(case["envelope_hex"])
    assert envelope_tag(envelope) == TAG_POINTER
    ref = decode_pointer(envelope)
    assert (ref.object_id, ref.size, ref.sha256) == (case["object_id"], case["size"], case["sha256"])
    assert len(envelope) == VECTORS["pointer_fixed_bytes"] + len(case["object_id"])


@pytest.mark.parametrize("case", VECTORS["malformed"], ids=lambda c: c["name"])
def test_malformed_cases_are_refused(case: dict[str, str]) -> None:
    """Every malformed case raises StorageEnvelopeError."""
    envelope = bytes.fromhex(case["envelope_hex"])
    with pytest.raises(StorageEnvelopeError):
        if envelope_tag(envelope) == TAG_POINTER:
            decode_pointer(envelope)
    if case["error"] in ("empty", "unknown_tag"):
        with pytest.raises(StorageEnvelopeError):
            envelope_tag(envelope)
