def _cases() -> str:
    """``nestedCases``: one entry per generated record with a ``Nested`` field."""
    lines = [
        "// nestedCases holds every generated record that embeds a nested record as",
        "// binary, by protocol name.",
        "var nestedCases = map[string]func(*testing.T, []byte, string, []byte, any){",
    ]
    schemas = []
    found = False
    for record in go_types.build_records():
        nested = [f for f in record.fields if f.nested]
        if not nested:
            continue
        if len(nested) != 1 or nested[0].nullable or nested[0].nested != "BindRequest":
            raise GeneratorError(f"{record.name}: the conformance test expects one non-null nested BindRequest")
        found = True
        f = nested[0]
        lines += [
            f'\t"{record.py_name}": nestedCase[generated.{record.name}]{{',
            f"\t\tnested: func(r generated.{record.name}) generated.Nested[generated.BindRequest] {{",
            f"\t\t\treturn r.{f.name}",
            "\t\t},",
            f"\t\tvalue: func(r generated.{record.name}) (generated.BindRequest, error) {{",
            f"\t\t\treturn r.{f.name}Value()",
            "\t\t},",
            "\t}.run,",
        ]
        schemas.append(record.name)
    if not found:
        raise GeneratorError("no generated Go record has a nested-binary field")
    lines.append("}")
    lines += [
        "",
        "// Each record with a Nested field still derives its protocol schema (the",
        "// wrapper is a binary column).",
        "func TestNestedBinarySchemas(t *testing.T) {",
        "\tfor _, tc := range []struct {",
        "\t\tname   string",
        "\t\tvalue  any",
        "\t\tschema *arrow.Schema",
        "\t}{",
    ]
    for name in ["BindRequest", "ArgumentsLocation", *schemas]:
        lines.append(f'\t\t{{"{name}", generated.{name}{{}}, generated.{name}Schema}},')
    lines += [
        "\t} {",
        "\t\tgot, err := vgirpc.SchemaForStruct(reflect.TypeOf(tc.value))",
        "\t\tif err != nil {",
        '\t\t\tt.Fatalf("deriving %s: %v", tc.name, err)',
        "\t\t}",
        "\t\tif !got.Equal(tc.schema) {",
        '\t\t\tt.Fatalf("%s derives\\n%v\\nbut the protocol declares\\n%v", tc.name, got, tc.schema)',
        "\t\t}",
        "\t}",
        "}",
    ]
    return "\n".join(lines) + "\n"


def emit(out: TextIO) -> None:
    """Emit the Go conformance test."""
    body = _HEAD + _cases() + _TAIL
    out.write(
        provenance_comment(
            generator_module="vgi.codegen.go_nested_test",
            generator_command="python -m vgi.codegen.go_nested_test",
            generator_version=GENERATOR_VERSION,
            regen_command_lines=["uv run --project ~/Development/vgi-python python scripts/regen_generated.py"],
            body=body,
        )
    )
    out.write("\n")
    out.write(body)


def main() -> None:
    """Write the test to stdout."""
    buf = io.StringIO()
    emit(buf)
    sys.stdout.write(buf.getvalue())


if __name__ == "__main__":
    main()
