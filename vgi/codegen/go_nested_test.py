r"""Emit Go's nested-binary conformance test (vgi docs/large-values-3.4.md §3.4).

The test runs vgi-go's generated records (`vgi.codegen.go_types`) over the
corpus `vgi.codegen.nested_binary_fixtures` checks into
``conformance/nested-binary/``:

1. byte identity: decode each embedding fixture, access ``bind_call`` and
   compare its fields with ``expected.json``, re-encode, and require the
   re-encoded ``bind_call`` column to equal ``bind_call.bin`` -- with and
   without accessing the value first;
2. typed construction: build a ``BindRequest`` from fields, wrap it with
   ``NestedOf``, embed it in an ``InitRequest``, encode, decode, access, and
   compare; the same wrapper encodes to identical bytes twice;
3. null arguments: ``bind-arguments-null.arrow`` decodes with ``Arguments``
   nil (asserted explicitly: a Go ``[]byte`` would accept nil silently) and
   the location set; the two invalid binds decode to the combinations a worker
   must refuse.

Spec test 4 (re-encoding after opening sealed opaque data) runs through
vgi-go's request-entry code and lives with it, not here.

It imports only the generated package, vgi-rpc-go and arrow-go, so it builds
whatever state the rest of vgi-go is in. The embedding records are derived
from the generated model (every record with a ``Nested`` field).

.. code-block:: bash

   uv run --project ~/Development/vgi-python python scripts/regen_generated.py
"""

